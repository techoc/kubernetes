package serviceaccount

import (
	"sync"

	"k8s.io/component-base/metrics"
	"k8s.io/component-base/metrics/legacyregistry"
)

// kubeServiceAccountSubsystem 是所有 ServiceAccount 相关指标的子系统名称。
const kubeServiceAccountSubsystem = "serviceaccount"

var (
	// legacyTokensTotal 记录没有 audience claim 的旧版 Token 使用次数。
	// 这类 Token 使用 implicit audiences（API Server 的 issuer），是弃用迁移的目标。
	legacyTokensTotal = metrics.NewCounter(
		&metrics.CounterOpts{
			Subsystem:      kubeServiceAccountSubsystem,
			Name:           "legacy_tokens_total",
			Help:           "Cumulative legacy service account tokens used",
			StabilityLevel: metrics.BETA,
		},
	)

	// staleTokensTotal 记录超过 warnafter 阈值但仍在使用的项目化 Token 次数。
	// 客户端应该在 warnafter 后刷新 Token，超过说明客户端没有及时刷新。
	staleTokensTotal = metrics.NewCounter(
		&metrics.CounterOpts{
			Subsystem:      kubeServiceAccountSubsystem,
			Name:           "stale_tokens_total",
			Help:           "Cumulative stale projected service account tokens used",
			StabilityLevel: metrics.BETA,
		},
	)

	// manuallyCreatedTokensTotal 记录手动创建的 Secret-based Token 使用次数。
	// 用户手动创建并关联到 ServiceAccount 的 Secret，不是自动生成的。
	manuallyCreatedTokensTotal = metrics.NewCounter(
		&metrics.CounterOpts{
			Subsystem:      kubeServiceAccountSubsystem,
			Name:           "legacy_manual_token_uses_total",
			Help:           "Cumulative manually created legacy tokens used",
			StabilityLevel: metrics.ALPHA,
		},
	)

	// autoGeneratedTokensTotal 记录自动生成的 Secret-based Token 使用次数。
	// ServiceAccount 控制器自动创建并关联到 ServiceAccount.Secrets 的 Secret。
	autoGeneratedTokensTotal = metrics.NewCounter(
		&metrics.CounterOpts{
			Subsystem:      kubeServiceAccountSubsystem,
			Name:           "legacy_auto_token_uses_total",
			Help:           "Cumulative auto-generated legacy tokens used",
			StabilityLevel: metrics.ALPHA,
		},
	)

	// invalidatedAutoTokensTotal 记录已被标记失效的自动生成 Token 的使用尝试次数。
	// 设置了 kubernetes.io/legacy-token-invalid-since label 的 Secret 对应的 Token。
	invalidatedAutoTokensTotal = metrics.NewCounter(
		&metrics.CounterOpts{
			Subsystem:      kubeServiceAccountSubsystem,
			Name:           "invalid_legacy_auto_token_uses_total",
			Help:           "Cumulative invalid auto-generated legacy tokens used",
			StabilityLevel: metrics.ALPHA,
		},
	)

	// validTokensTotal 记录在 warnafter 阈值内的有效项目化 Token 使用次数。
	validTokensTotal = metrics.NewCounter(
		&metrics.CounterOpts{
			Subsystem:      kubeServiceAccountSubsystem,
			Name:           "valid_tokens_total",
			Help:           "Cumulative valid projected service account tokens used",
			StabilityLevel: metrics.BETA,
		},
	)
)

var registerMetricsOnce sync.Once

// RegisterMetrics 注册所有 ServiceAccount Token 相关的指标。
// 使用 sync.Once 确保只注册一次，避免重复注册错误。
func RegisterMetrics() {
	registerMetricsOnce.Do(func() {
		legacyregistry.MustRegister(legacyTokensTotal)
		legacyregistry.MustRegister(staleTokensTotal)
		legacyregistry.MustRegister(manuallyCreatedTokensTotal)
		legacyregistry.MustRegister(autoGeneratedTokensTotal)
		legacyregistry.MustRegister(invalidatedAutoTokensTotal)
		legacyregistry.MustRegister(validTokensTotal)
	})
}
