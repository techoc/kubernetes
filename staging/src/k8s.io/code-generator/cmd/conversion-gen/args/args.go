// Package args 定义 conversion-gen 的命令行参数、默认值、flag 注册与校验逻辑。
package args

import (
	"fmt"

	"github.com/spf13/pflag"

	"k8s.io/code-generator/pkg/apidefinitions"
	"k8s.io/gengo/v2"
)

// DefaultBasePeerDirs 是几乎人人都会用到的 peer 目录，即来自 apimachinery 的那些。
// 这些包定义了公共元数据和运行时类型，转换函数需要能识别它们。
var DefaultBasePeerDirs = []string{
	"k8s.io/apimachinery/pkg/apis/meta/v1",
	"k8s.io/apimachinery/pkg/conversion",
	"k8s.io/apimachinery/pkg/runtime",
}

// Args 汇总 conversion-gen 的命令行参数。
type Args struct {
	// 生成结果的文件名。
	OutputFile string

	// 几乎所有使用者都会用到的基础 peer 目录（Kubernetes core 之外，例如 apimachinery）。
	// 声明 peer 目录是为了让生成器能发现外部包中手写的转换函数。
	BasePeerDirs []string

	// 应用特有的额外 peer 目录。声明 peer 目录是为了让生成器能发现外部包中
	// 手写的转换函数。
	ExtraPeerDirs []string

	// SkipUnsafe 指示是否跳过生成 unsafe 转换以提高效率。unsafe 操作在允许的
	// 范围内做直接指针赋值，等价于 Golang 社区提议的“结构完全相同时可直接赋值”。
	SkipUnsafe bool

	// GoHeaderFile 是生成代码的 boilerplate 头文件路径。
	GoHeaderFile string

	// GeneratedBuildTag 是标识该生成器产物的 Go build tag。每个生成器应使用不同的
	// tag，不同的生成器组（依赖 Kube 生成的 external API）也应保持 tag 互异。
	GeneratedBuildTag string

	apidefinitions.LintArgs
}

// New 返回生成器的默认参数。LintRules 默认为空以保持对第三方生成器标签的兼容性。
func New() *Args {
	return &Args{
		BasePeerDirs:      DefaultBasePeerDirs,
		SkipUnsafe:        false,
		GeneratedBuildTag: gengo.StdBuildTag,
	}
}

// AddFlags 把生成器参数注册到 flag set。默认值为空字符串表示使用 gengo 的
// 默认值（见 New）。
func (args *Args) AddFlags(fs *pflag.FlagSet) {
	fs.StringVar(&args.OutputFile, "output-file", "generated.conversion.go",
		"the name of the file to be generated")
	fs.StringSliceVar(&args.BasePeerDirs, "base-peer-dirs", args.BasePeerDirs,
		"Comma-separated list of apimachinery import paths which are considered, after tag-specified peers, for conversions. Only change these if you have very good reasons.")
	fs.StringSliceVar(&args.ExtraPeerDirs, "extra-peer-dirs", args.ExtraPeerDirs,
		"Application specific comma-separated list of import paths which are considered, after tag-specified peers and base-peer-dirs, for conversions.")
	fs.BoolVar(&args.SkipUnsafe, "skip-unsafe", args.SkipUnsafe,
		"If true, will not generate code using unsafe pointer conversions; resulting code may be slower.")
	fs.StringVar(&args.GoHeaderFile, "go-header-file", "",
		"the path to a file containing boilerplate header text; the string \"YEAR\" will be replaced with the current 4-digit year")
	fs.StringVar(&args.GeneratedBuildTag, "build-tag", args.GeneratedBuildTag, "A Go build tag to use to identify files generated by this command. Should be unique.")
	apidefinitions.AddFlags(&args.LintArgs, fs)
}

// Validate 校验参数：输出文件名必填，且 lint 规则名必须可被识别。
func (args *Args) Validate() error {
	if len(args.OutputFile) == 0 {
		return fmt.Errorf("--output-file must be specified")
	}
	if err := apidefinitions.ValidateFlags(args.LintRules); err != nil {
		return err
	}
	return nil
}
