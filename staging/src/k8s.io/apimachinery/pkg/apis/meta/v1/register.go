package v1

import (
	"k8s.io/apimachinery/pkg/runtime"
	"k8s.io/apimachinery/pkg/runtime/schema"
	utilruntime "k8s.io/apimachinery/pkg/util/runtime"
)

// GroupName is the group name for this API.
//
// meta.k8s.io 不是真实资源组，只承载所有资源共用的元数据类型
// （Status、APIGroup 等）。
const GroupName = "meta.k8s.io"

var (
	// localSchemeBuilder is used to make compiler happy for autogenerated
	// conversions. However, it's not used.
	//
	// 生成代码引用这个变量，但此处没有任何对象需要自动生成转换。
	schemeBuilder      runtime.SchemeBuilder
	localSchemeBuilder = &schemeBuilder
)

// SchemeGroupVersion is group version used to register these objects
var SchemeGroupVersion = schema.GroupVersion{Group: GroupName, Version: "v1"}

// Unversioned is group version for unversioned API objects
// TODO: this should be v1 probably
//
// 空 group 是无版本对象（Status 等）的历史约定，不能改成 meta.k8s.io，
// 否则会破坏已发布的 API 路径。
var Unversioned = schema.GroupVersion{Group: "", Version: "v1"}

// WatchEventKind is name reserved for serializing watch events.
const WatchEventKind = "WatchEvent"

// Kind takes an unqualified kind and returns a Group qualified GroupKind
func Kind(kind string) schema.GroupKind {
	return SchemeGroupVersion.WithKind(kind).GroupKind()
}

// scheme is the registry for the common types that adhere to the meta v1 API spec.
var scheme = runtime.NewScheme()

// ParameterCodec knows about query parameters used with the meta v1 API spec.
//
// 用于把 ListOptions/GetOptions 等对象与 URL 查询参数互转，供各
// API 服务器通用地处理分页与字段选择。
var ParameterCodec = runtime.NewParameterCodec(scheme)

// optionsTypes 列出所有以查询参数形式出现在所有资源请求上的选项类型；
// 它们需要在每个 group/version 下注册，因为请求路径属于具体资源。
var optionsTypes = []runtime.Object{
	&ListOptions{},
	&GetOptions{},
	&DeleteOptions{},
	&CreateOptions{},
	&UpdateOptions{},
	&PatchOptions{},
}

// AddToGroupVersion registers common meta types into schemas.
//
// 每个 API 服务器的 scheme 都需要调用一次，用来注册该 group/version 下
// 通用的 watch 事件与选项类型。watch 事件同时注册外部与 Internal 版本，
// 以便解码后的对象可以参与版本转换。
func AddToGroupVersion(scheme *runtime.Scheme, groupVersion schema.GroupVersion) {
	scheme.AddKnownTypeWithName(groupVersion.WithKind(WatchEventKind), &WatchEvent{})
	scheme.AddKnownTypeWithName(
		schema.GroupVersion{Group: groupVersion.Group, Version: runtime.APIVersionInternal}.WithKind(WatchEventKind),
		&InternalEvent{},
	)
	// Supports legacy code paths, most callers should use metav1.ParameterCodec for now
	scheme.AddKnownTypes(groupVersion, optionsTypes...)
	// Register Unversioned types under their own special group
	scheme.AddUnversionedTypes(Unversioned,
		&Status{},
		&APIVersions{},
		&APIGroupList{},
		&APIGroup{},
		&APIResourceList{},
	)

	// register manually. This usually goes through the SchemeBuilder, which we cannot use here.
	// 转换与默认值函数由生成代码提供，但这里没有 SchemeBuilder，故显式注册；
	// 失败会 panic，属于初始化期不可恢复的编程错误。
	utilruntime.Must(RegisterConversions(scheme))
	utilruntime.Must(RegisterDefaults(scheme))
}

// AddMetaToScheme registers base meta types into schemas.
//
// 只注册 Table/PartialObjectMetadata 这类“元数据视图”对象，通常由
// 需要支持服务器端表输出的组件调用；不会注册无版本类型。
func AddMetaToScheme(scheme *runtime.Scheme) error {
	scheme.AddKnownTypes(SchemeGroupVersion,
		&Table{},
		&TableOptions{},
		&PartialObjectMetadata{},
		&PartialObjectMetadataList{},
	)

	return nil
}

func init() {
	// 包级默认 scheme 仅用于 ParameterCodec，注册选项类型即可。
	scheme.AddUnversionedTypes(SchemeGroupVersion, optionsTypes...)

	utilruntime.Must(AddMetaToScheme(scheme))

	// register manually. This usually goes through the SchemeBuilder, which we cannot use here.
	// 默认值同样由生成代码提供，这里显式注册。
	utilruntime.Must(RegisterDefaults(scheme))
}
